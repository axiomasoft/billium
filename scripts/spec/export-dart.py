#!/usr/bin/env python3
"""Export the data of a spec revision into the Dart package billium_contracts.

Writes lib/src/generated/*.g.dart: the currency table, the problem-code enum, the schema bundle with the envelope
registry and the envelope classes. Generated files carry `// dart format off`; they are checked here, not by dart format.
Writes by default; --check compares without writing and exits 1 on drift.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from export_common import (  # noqa: E402
    DEFAULT_REVISION,
    ROOT,
    SUPPORTED_REVISIONS,
    Envelope,
    ExportError,
    Revision,
    pascal,
    revision_hash,
    write_or_check,
)

DEFAULT_OUT = ROOT / "packages/contracts-dart"
TOOL = "export-dart"

HELPERS = {
    ("string", True): "requireString",
    ("string", False): "optionalString",
    ("int", True): "requireInt",
    ("int", False): "optionalInt",
    ("money", True): "requireMoney",
    ("money", False): "optionalMoney",
    ("object", True): "requireObject",
    ("object", False): "optionalObject",
    ("list", True): "requireList",
    ("list", False): "optionalList",
    ("bool", True): "requireBool",
    ("bool", False): "optionalBool",
}
DART_TYPES = {"string": "String", "int": "int", "money": "Money", "object": "Map<String, Object?>", "list": "List<Object?>", "bool": "bool"}


def header(revision: Revision, source: str) -> str:
    return (
        "// dart format off\n"
        f"// Generated by scripts/spec/{TOOL}.py from spec/revisions/{revision.name}/{source}. Do not edit.\n\n"
    )


def lower_camel(code: str) -> str:
    name = pascal(code)
    return name[:1].lower() + name[1:]


def render_currencies(revision: Revision) -> str:
    rows = "".join(
        f"  '{row['code']}': {row['scale']},\n"
        for row in sorted(revision.currencies, key=lambda row: str(row["code"]))
    )
    return (
        header(revision, "currencies.json")
        + "/// Fraction digits of the minor unit by ISO 4217 code (D19).\n"
        + f"const Map<String, int> currencyScales = {{\n{rows}}};\n"
    )


def render_problem_codes(revision: Revision) -> str:
    def literal(value: object) -> str:
        return str(value).lower() if isinstance(value, bool) else f"'{value}'"

    cases = ",\n".join(
        "  {name}({args})".format(
            name=lower_camel(str(entry["code"])),
            args=", ".join(literal(entry[key]) for key in ("code", "category", "retryable", "sameKey", "receipt")),
        )
        for entry in revision.codes
    )
    return (
        header(revision, "problem-codes.json")
        + "/// Problem codes of the revision with their registry entry: category, retryable, sameKey and receipt policy (D31).\n"
        + f"enum ProblemCode {{\n{cases};\n\n"
        + "  const ProblemCode(\n    this.value,\n    this.category,\n    this.retryable,\n    this.sameKey,\n    this.receipt,\n  );\n\n"
        + "  /// The wire code, for example `billium.validation.invalid`.\n  final String value;\n"
        + "  final String category;\n  final bool retryable;\n  final bool sameKey;\n"
        + "  /// `stored` or `none`.\n  final String receipt;\n\n"
        + "  /// The code for a wire value, or null when the registry has none.\n"
        + "  static ProblemCode? tryParse(String value) {\n"
        + "    for (final code in values) {\n      if (code.value == value) return code;\n    }\n    return null;\n  }\n}\n"
    )


def raw_string(text: str) -> str:
    if "'''" in text:
        raise ExportError("generated data contains a triple quote")
    return f"r'''{text.rstrip(chr(10))}'''"


def render_spec_data(revision: Revision) -> str:
    registry = revision.registry_text()
    supported = ", ".join(f"'{rev}'" for rev in SUPPORTED_REVISIONS)
    hashes = "".join(
        f"  '{rev}': '{revision_hash(ROOT / 'spec/revisions' / rev)}',\n"
        for rev in SUPPORTED_REVISIONS
    )
    schemas_by_rev = []
    registries_by_rev = []
    for rev_name in SUPPORTED_REVISIONS:
        rev = revision if rev_name == revision.name else Revision(ROOT / "spec/revisions" / rev_name)
        schemas_by_rev.append(f"  '{rev_name}': {raw_string(rev.bundle_text())},\n")
        registries_by_rev.append(f"  '{rev_name}': {raw_string(rev.registry_text())},\n")
    return (
        header(revision, "revision.lock.json")
        + f"/// The revision the package implements.\nconst String specRevision = '{revision.name}';\n\n"
        + f"/// Supported spec revisions.\nconst List<String> supportedSpecRevisions = [{supported}];\n\n"
        + f"/// Lock hashes by spec revision.\nconst Map<String, String> specRevisionHashes = {{\n{hashes}}};\n\n"
        + f"/// Every schema of the revision by `$id` (JSON).\nconst String schemasJson = {raw_string(revision.bundle_text())};\n\n"
        + "/// Envelope registry by schema name (JSON): schema `$id` and the variants that pick a class.\n"
        + f"const String envelopeRegistryJson = {raw_string(registry)};\n\n"
        + f"/// Schema bundles by spec revision.\nconst Map<String, String> schemasJsonByRevision = {{\n{''.join(schemas_by_rev)}}};\n\n"
        + f"/// Envelope registries by spec revision.\nconst Map<String, String> envelopeRegistryJsonByRevision = {{\n{''.join(registries_by_rev)}}};\n"
    )


def render_envelope(envelope: Envelope) -> str:
    members = [member for member in envelope.members if member.name != "schema"]
    ordered = [m for m in members if m.required] + [m for m in members if not m.required]
    constructor = "".join(
        f"    {'required ' if m.required else ''}this.{m.name},\n" for m in ordered
    )
    arguments = "".join(
        f"        {m.name}: {HELPERS[(m.kind, m.required)]}(raw, '{m.name}'),\n" for m in ordered
    )
    fields = "".join(
        f"  final {DART_TYPES[m.kind]}{'' if m.required else '?'} {m.name};\n" for m in ordered
    )
    return (
        f"/// `{envelope.schema}`.\nfinal class {envelope.class_name} extends Envelope {{\n"
        f"  static const String schemaName = '{envelope.schema}';\n\n"
        f"  {envelope.class_name}({{\n    required super.raw,\n{constructor}  }}) : super(schema: schemaName);\n\n"
        f"  /// Builds the typed envelope from an object that passed the schema of the revision.\n"
        f"  factory {envelope.class_name}.fromRaw(Map<String, Object?> raw) => {envelope.class_name}(\n"
        f"        raw: raw,\n{arguments}      );\n\n"
        f"{fields}}}\n"
    )


def render_envelopes(revision: Revision) -> str:
    envelopes = revision.envelopes()
    factories = "".join(
        f"  '{envelope.class_name}': {envelope.class_name}.fromRaw,\n" for envelope in envelopes
    )
    classes = "\n".join(render_envelope(envelope) for envelope in envelopes)
    return (
        header(revision, "schema/**")
        + "import '../envelope.dart';\nimport '../fields.dart';\nimport '../money.dart';\n\n"
        + "/// Builders of the envelope classes by class name, for the registry.\n"
        + f"const Map<String, Envelope Function(Map<String, Object?>)> envelopeBuilders = {{\n{factories}}};\n\n"
        + classes
    )


def build(revision: Revision, out: Path) -> dict[Path, str]:
    generated = out / "lib/src/generated"
    return {
        generated / "currencies.g.dart": render_currencies(revision),
        generated / "problem_codes.g.dart": render_problem_codes(revision),
        generated / "spec_data.g.dart": render_spec_data(revision),
        generated / "envelopes.g.dart": render_envelopes(revision),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", type=Path, default=DEFAULT_REVISION)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="package directory")
    parser.add_argument("--check", action="store_true", help="compare only, never write")
    args = parser.parse_args()

    try:
        files = build(Revision(args.revision), args.out)
    except (OSError, KeyError, TypeError, ValueError, ExportError) as error:
        print(f"{TOOL}: {error}", file=sys.stderr)
        return 1
    return write_or_check(files, args.check, TOOL, owned=((args.out / "lib/src/generated", "*.g.dart"),))


if __name__ == "__main__":
    sys.exit(main())
