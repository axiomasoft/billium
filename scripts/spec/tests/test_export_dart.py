"""Self-tests of scripts/spec/export-dart.py: determinism, --check on drift, the shape of the generated Dart.

Run: python3 -m unittest discover -s scripts/spec/tests -p test_export_dart.py -v
Each test exports into a temporary package directory from a temporary copy of the revision.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCRIPT = ROOT / "scripts/spec/export-dart.py"
REV = ROOT / "spec/revisions/2026-10"


class ExportDartTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="billium-export-dart-"))
        self.addCleanup(shutil.rmtree, self.tmp)
        self.rev = self.tmp / REV.name
        shutil.copytree(REV, self.rev)
        self.out = self.tmp / "contracts-dart"
        self.generated = self.out / "lib/src/generated"

    def export(self, *args: str | Path) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(SCRIPT), "--revision", str(self.rev), "--out", str(self.out), *map(str, args)],
            capture_output=True,
            text=True,
            check=False,
        )

    def snapshot(self) -> dict[str, bytes]:
        return {path.relative_to(self.out).as_posix(): path.read_bytes() for path in sorted(self.out.rglob("*")) if path.is_file()}

    def test_committed_package_is_fresh(self) -> None:
        result = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_two_exports_are_identical_and_check_passes(self) -> None:
        self.assertEqual(self.export().returncode, 0)
        first = self.snapshot()
        self.assertEqual(self.export().returncode, 0)
        self.assertEqual(self.snapshot(), first)
        self.assertEqual(self.export("--check").returncode, 0)

    def test_generated_files(self) -> None:
        self.export()
        files = self.snapshot()
        self.assertEqual(
            sorted(name.rsplit("/", 1)[1] for name in files),
            ["currencies.g.dart", "envelopes.g.dart", "problem_codes.g.dart", "spec_data.g.dart"],
        )
        for name, text in files.items():
            self.assertTrue(text.decode().startswith("// dart format off\n// Generated by scripts/spec/export-dart.py"), name)
        envelopes = files["lib/src/generated/envelopes.g.dart"].decode()
        self.assertEqual(len(re.findall(r"^final class \w+ extends Envelope", envelopes, re.M)), 58)
        self.assertIn("final class FeedBootstrapAck extends Envelope", envelopes)
        self.assertIn("final class MetricVersion extends Envelope", envelopes)
        self.assertIn("final class RatedBasis extends Envelope", envelopes)
        self.assertIn("final class ExternalImport extends Envelope", envelopes)
        self.assertIn("final class ExternalImportManifest extends Envelope", envelopes)
        self.assertIn("final class ExternalImportPreview extends Envelope", envelopes)
        self.assertIn("required this.money,", envelopes)
        self.assertIn("  final Money money;\n", envelopes)
        self.assertIn("  final String? returnContextRef;\n", envelopes)
        self.assertNotRegex("\n".join(text.decode() for text in files.values()), r"\bdouble\b")
        codes = files["lib/src/generated/problem_codes.g.dart"].decode()
        self.assertIn("idempotencyInFlight('billium.idempotency.in_flight', 'idempotency', true, true, 'none')", codes)
        data = files["lib/src/generated/spec_data.g.dart"].decode()
        self.assertIn("const String specRevision = '2026-10';", data)
        registry = json.loads(re.search(r"envelopeRegistryJson = r'''(.*?)'''", data, re.S).group(1))  # type: ignore[union-attr]
        self.assertEqual(
            [entry["class"] for entry in registry["payment.find.v1"]["variants"]],
            ["FindResult", "FindOperation"],
        )

    def assert_stale(self, needle: str) -> None:
        result = self.export("--check")
        self.assertEqual(result.returncode, 1, result.stderr)
        self.assertIn("stale", result.stderr)
        self.assertIn(needle, result.stderr)

    def test_check_detects_an_edited_generated_file(self) -> None:
        self.export()
        target = self.generated / "problem_codes.g.dart"
        target.write_text(target.read_text(encoding="utf-8") + "// hand edit\n", encoding="utf-8")
        before = self.snapshot()
        self.assert_stale("problem_codes.g.dart")
        self.assertEqual(self.snapshot(), before, "--check wrote a file")

    def test_check_detects_a_missing_and_a_leftover_file(self) -> None:
        self.export()
        (self.generated / "currencies.g.dart").unlink()
        (self.generated / "retired.g.dart").write_text("// old\n", encoding="utf-8")
        result = self.export("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("currencies.g.dart", result.stderr)
        self.assertIn("retired.g.dart", result.stderr)
        self.assertEqual(self.export().returncode, 0)
        self.assertFalse((self.generated / "retired.g.dart").exists(), "a leftover generated file is removed")

    def test_check_detects_a_changed_spec(self) -> None:
        self.export()
        path = self.rev / "problem-codes.json"
        document = json.loads(path.read_text(encoding="utf-8"))
        document[0]["retryable"] = not document[0]["retryable"]
        path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        self.assert_stale("problem_codes.g.dart")

    def test_unmappable_member_is_refused(self) -> None:
        path = self.rev / "schema/payment/cancel.v1.json"
        document = json.loads(path.read_text(encoding="utf-8"))
        document["properties"]["operationRef"] = {"type": "number"}
        path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        result = self.export()
        self.assertEqual(result.returncode, 1)
        self.assertIn("cannot map schema", result.stderr)


if __name__ == "__main__":
    unittest.main()
