#!/usr/bin/env python3
"""Export the data of a spec revision into the PHP package axiomasoft/billium-contracts.

Writes resources/ (currency table, schema bundle, envelope registry) and the generated PHP types
(ProblemCode, envelope classes). The package reads nothing outside itself after installation.
Writes by default; --check compares without writing and exits 1 on drift.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from export_common import (  # noqa: E402
    DEFAULT_REVISION,
    ROOT,
    Envelope,
    ExportError,
    Revision,
    pascal,
    write_or_check,
)

DEFAULT_OUT = ROOT / "packages/contracts"
TOOL = "export-php"

HELPERS = {
    ("string", True): "string",
    ("string", False): "optString",
    ("int", True): "int",
    ("int", False): "optInt",
    ("money", True): "money",
    ("money", False): "optMoney",
    ("object", True): "object",
    ("object", False): "optObject",
    ("list", True): "list",
    ("list", False): "optList",
    ("bool", True): "bool",
    ("bool", False): "optBool",
}
PHP_TYPES = {"string": "string", "int": "int", "money": "Money", "object": "\\stdClass", "list": "array", "bool": "bool"}


def header(revision: Revision, source: str) -> str:
    return f"Generated by scripts/spec/{TOOL}.py from spec/revisions/{revision.name}/{source}. Do not edit."


def render_currencies(revision: Revision) -> str:
    rows = "".join(
        f"    '{row['code']}' => {row['scale']},\n"
        for row in sorted(revision.currencies, key=lambda row: str(row["code"]))
    )
    return (
        "<?php\n\ndeclare(strict_types=1);\n\n"
        f"// {header(revision, 'currencies.json')}\n\n"
        f"return [\n{rows}];\n"
    )


def render_problem_code(revision: Revision) -> str:
    cases = "".join(f"    case {pascal(str(entry['code']))} = '{entry['code']}';\n" for entry in revision.codes)

    def method(name: str, return_type: str, render) -> str:
        arms = "".join(
            f"            self::{pascal(str(entry['code']))} => {render(entry[name])},\n" for entry in revision.codes
        )
        return (
            f"    public function {name}(): {return_type}\n    {{\n"
            f"        return match ($this) {{\n{arms}        }};\n    }}\n"
        )

    def text(value: object) -> str:
        return f"'{value}'"

    def boolean(value: object) -> str:
        return "true" if value else "false"

    methods = "\n".join(
        [
            method("category", "string", text),
            method("retryable", "bool", boolean),
            method("sameKey", "bool", boolean),
            method("receipt", "string", text),
        ]
    )
    return (
        "<?php\n\ndeclare(strict_types=1);\n\nnamespace Billium\\Contracts\\Enums;\n\n"
        "use Packman\\Attributes\\Api;\n\n"
        f"/**\n * {header(revision, 'problem-codes.json')}\n */\n"
        f"#[Api(since: '1.0')]\nenum ProblemCode: string\n{{\n{cases}\n{methods}}}\n"
    )


def render_envelope(revision: Revision, envelope: Envelope) -> str:
    members = [member for member in envelope.members if member.name != "schema"]
    ordered = [m for m in members if m.required] + [m for m in members if not m.required]
    uses = {"Billium\\Contracts\\Data\\Envelope", "Packman\\Attributes\\Api"}
    if any(member.kind == "money" for member in members):
        uses.add("Billium\\Contracts\\Data\\Money")
    use_lines = "".join(f"use {name};\n" for name in sorted(uses))

    list_docs = [f"     * @param  list<mixed>  ${m.name}" for m in ordered if m.kind == "list"]
    constructor_doc = "    /**\n" + "\n".join(list_docs) + "\n     */\n" if list_docs else ""
    params = "".join(
        f"        public {'' if m.required else '?'}{PHP_TYPES[m.kind]} ${m.name}{'' if m.required else ' = null'},\n"
        for m in ordered
    )
    arguments = "".join(
        f"            {m.name}: self::{HELPERS[(m.kind, m.required)]}($raw, '{m.name}'),\n" for m in ordered
    )
    return (
        "<?php\n\ndeclare(strict_types=1);\n\nnamespace Billium\\Contracts\\Data\\Envelopes;\n\n"
        f"{use_lines}\n"
        f"/**\n * {header(revision, 'schema/' + envelope.source)}\n */\n"
        f"#[Api(since: '1.0')]\nfinal readonly class {envelope.class_name} extends Envelope\n{{\n"
        f"    public const string SCHEMA = '{envelope.schema}';\n\n"
        f"{constructor_doc}    public function __construct(\n        \\stdClass $raw,\n{params}    ) {{\n"
        "        parent::__construct(raw: $raw, schema: self::SCHEMA);\n    }\n\n"
        "    public static function fromRaw(\\stdClass $raw): self\n    {\n"
        f"        return new self(\n            raw: $raw,\n{arguments}        );\n    }}\n}}\n"
    )


def render_spec_revision(revision: Revision) -> str:
    return (
        "<?php\n\ndeclare(strict_types=1);\n\nnamespace Billium\\Contracts\\Contracts;\n\n"
        "use Packman\\Attributes\\Api;\n\n"
        f"/**\n * {header(revision, 'revision.lock.json')}\n */\n"
        f"#[Api(since: '1.0')]\nfinal class SpecRevision\n{{\n    public const string CURRENT = '{revision.name}';\n}}\n"
    )


def build(revision: Revision, out: Path) -> dict[Path, str]:
    files: dict[Path, str] = {
        out / "resources/currencies.php": render_currencies(revision),
        out / "resources/spec/schemas.json": revision.bundle_text(),
        out / "resources/spec/envelopes.json": revision.registry_text(),
        out / "src/Enums/ProblemCode.php": render_problem_code(revision),
        out / "src/Contracts/SpecRevision.php": render_spec_revision(revision),
    }
    for envelope in revision.envelopes():
        files[out / f"src/Data/Envelopes/{envelope.class_name}.php"] = render_envelope(revision, envelope)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", type=Path, default=DEFAULT_REVISION)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="package directory")
    parser.add_argument("--check", action="store_true", help="compare only, never write")
    args = parser.parse_args()

    try:
        files = build(Revision(args.revision), args.out)
    except (OSError, KeyError, TypeError, ValueError, ExportError) as error:
        print(f"{TOOL}: {error}", file=sys.stderr)
        return 1
    owned = ((args.out / "src/Data/Envelopes", "*.php"), (args.out / "resources", "*.php"), (args.out / "resources/spec", "**/*"))
    return write_or_check(files, args.check, TOOL, owned=owned)


if __name__ == "__main__":
    sys.exit(main())
