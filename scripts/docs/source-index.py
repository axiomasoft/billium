#!/usr/bin/env python3
"""Generate docs/source-index/: one Markdown page per PHP package listing every source type.

Each entry carries the type kind, its Packman visibility attribute (Api/Spi/Internal) and the first sentence of
its docblock, so a reader can locate the right file without opening the package. The package import graph is
derived from `use Billium\\...` statements. Run with --check to fail when the committed pages are stale.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "source-index"
HEADER = "<!-- Generated by scripts/docs/source-index.py; do not edit. Regenerate: python3 scripts/docs/source-index.py -->"
SUMMARY_LIMIT = 160

TYPE_DECL = re.compile(
    r"^(?:(?:final|abstract|readonly)\s+)*(class|interface|trait|enum)\s+([A-Za-z_][A-Za-z0-9_]*)", re.M
)
DOCBLOCK = re.compile(r"/\*\*(.*?)\*/\s*((?:#\[[^\n]*\]\s*)*)$", re.S)
VISIBILITY = re.compile(r"#\[(Api|Spi|Internal)\b")
USE = re.compile(r"^use\s+Billium\\([A-Za-z]+)\\", re.M)


@dataclass(frozen=True)
class Package:
    name: str
    path: str
    namespace: str
    layer: str

    @property
    def slug(self) -> str:
        return self.name.split("/", 1)[1]

    @property
    def root_segment(self) -> str:
        return self.namespace.strip("\\").split("\\")[1]


@dataclass(frozen=True)
class Entry:
    directory: str
    name: str
    kind: str
    visibility: str
    summary: str


def load_packages() -> list[Package]:
    manifest = json.loads((ROOT / "packman.json").read_text(encoding="utf-8"))
    return [
        Package(item["name"], item["path"], item["namespace"], item.get("layer", ""))
        for item in manifest["packages"]
    ]


def summarize(docblock: str) -> str:
    lines = [re.sub(r"^\s*\*\s?", "", line).strip() for line in docblock.strip().splitlines()]
    paragraph: list[str] = []
    for line in lines:
        if line.startswith("@"):
            break
        if not line:
            if paragraph:
                break
            continue
        paragraph.append(line)
    text = re.sub(r"\{@\w+\s+([^}]+)\}", r"\1", " ".join(paragraph))
    match = re.search(r"^(.+?[.!?])(?:\s|$)", text)
    sentence = match.group(1) if match else text
    if len(sentence) > SUMMARY_LIMIT:
        sentence = sentence[: SUMMARY_LIMIT - 1].rstrip() + "…"
    return sentence.replace("|", "\\|")


def parse(source: str) -> tuple[str, str, str, str] | None:
    declaration = TYPE_DECL.search(source)
    if declaration is None:
        return None
    head = source[: declaration.start()]
    docblock = DOCBLOCK.search(head)
    attributes = docblock.group(2) if docblock else head[-400:]
    visibility = VISIBILITY.search(attributes)
    summary = summarize(docblock.group(1)) if docblock else ""
    return declaration.group(1), declaration.group(2), visibility.group(1) if visibility else "", summary


def collect(package: Package) -> tuple[list[Entry], set[str]]:
    src = ROOT / package.path / "src"
    entries: list[Entry] = []
    imports: set[str] = set()
    for file in sorted(src.rglob("*.php")):
        source = file.read_text(encoding="utf-8")
        imports.update(USE.findall(source))
        parsed = parse(source)
        if parsed is None:
            continue
        kind, name, visibility, summary = parsed
        directory = file.parent.relative_to(src).as_posix()
        entries.append(Entry("." if directory == "." else directory, name, kind, visibility, summary))
    imports.discard(package.root_segment)
    return entries, imports


def render_package(package: Package, entries: list[Entry]) -> str:
    lines = [
        HEADER,
        "",
        f"# {package.name}",
        "",
        f"Path `{package.path}/src`, namespace `{package.namespace}`, layer {package.layer}. {len(entries)} types.",
        "Visibility: **Api** public, **Spi** host extension point, *Internal* not for consumers.",
    ]
    current = None
    for entry in entries:
        if entry.directory != current:
            current = entry.directory
            lines += ["", f"## {current}", "", "| Type | Kind | Visibility | Summary |", "|---|---|---|---|"]
        link = f"[`{entry.name}`](../../{package.path}/src/{'' if current == '.' else current + '/'}{entry.name}.php)"
        visibility = {"Api": "**Api**", "Spi": "**Spi**", "Internal": "*Internal*"}.get(entry.visibility, "")
        lines.append(f"| {link} | {entry.kind} | {visibility} | {entry.summary} |")
    return "\n".join(lines) + "\n"


def render_overview(packages: list[Package], stats: dict[str, tuple[int, set[str]]]) -> str:
    segment_to_slug = {package.root_segment: package.slug for package in packages}
    lines = [
        HEADER,
        "",
        "# Source index",
        "",
        "One page per PHP package. Open the package page, find the directory, then read only the listed file.",
        "",
        "| Package | Layer | Types | Imports from |",
        "|---|---|---|---|",
    ]
    for package in packages:
        count, imports = stats[package.slug]
        targets = ", ".join(sorted(segment_to_slug.get(segment, segment) for segment in imports)) or "—"
        lines.append(f"| [{package.slug}]({package.slug}.md) | {package.layer} | {count} | {targets} |")
    return "\n".join(lines) + "\n"


def build() -> dict[Path, str]:
    packages = load_packages()
    pages: dict[Path, str] = {}
    stats: dict[str, tuple[int, set[str]]] = {}
    for package in packages:
        entries, imports = collect(package)
        stats[package.slug] = (len(entries), imports)
        pages[OUT / f"{package.slug}.md"] = render_package(package, entries)
    pages[OUT / "README.md"] = render_overview(packages, stats)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when docs/source-index is stale")
    args = parser.parse_args()
    pages = build()
    existing = set(OUT.glob("*.md")) if OUT.is_dir() else set()
    stale = sorted(
        [path for path, text in pages.items() if not path.is_file() or path.read_text(encoding="utf-8") != text]
        + [path for path in existing if path not in pages]
    )
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run: python3 scripts/docs/source-index.py", file=sys.stderr)
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path in existing - set(pages):
        path.unlink()
    for path, text in pages.items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
